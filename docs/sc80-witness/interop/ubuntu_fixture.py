#!/usr/bin/env python3
"""ubuntu_fixture.py -- write (or --check) tests/x/crypto/passwd/ubuntu_strings.lu.

Run inside sc80's pinned Ubuntu 24.04 image (libxcrypt 4.4.36, Python
3.12's `crypt` module, `mkpasswd` from `whois`). Every password and salt
is derived from SHA-256 of a numbered label, so the wolf row derives the
same ones at run time and no password is written into the row. Ubuntu's
crypt (and, for two rows, `mkpasswd -S`) makes each `$7$` string; those
strings are the row's generated test data.

    python3 -I ubuntu_fixture.py OUT.lu      write the row
    python3 -I ubuntu_fixture.py --check F   regenerate and compare with F
"""
import hashlib
import subprocess
import sys
import warnings

warnings.simplefilter("ignore", DeprecationWarning)
import crypt  # noqa: E402  (Ubuntu's libxcrypt, the black box)

A = "./0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"


def enc(b):
    """crypt's base-64 of octets, as learned black box (passwd's header)."""
    out = []
    for i in range(0, len(b), 3):
        chunk = b[i:i + 3]
        v = sum(x << (8 * j) for j, x in enumerate(chunk))
        for k in range({1: 2, 2: 3, 3: 4}[len(chunk)]):
            out.append(A[(v >> (6 * k)) & 63])
    return "".join(out)


def enc30(v):
    return "".join(A[(v >> (6 * k)) & 63] for k in range(5))


def password(i):
    return hashlib.sha256(f"sc80 ubuntu fixture password {i}".encode()).hexdigest()[:20]


def salt(i, octets):
    d = hashlib.sha512(f"sc80 ubuntu fixture salt {i}".encode()).digest()
    return enc(d[:octets])


# (row, n_log2, r, p, salt octets, maker)
ROWS = [
    (0, 10, 8, 1, 16, "crypt"),
    (1, 10, 8, 1, 16, "crypt"),
    (2, 10, 8, 1, 16, "crypt"),
    (3, 10, 8, 1, 16, "crypt"),
    (4, 14, 8, 1, 16, "crypt"),
    (5, 14, 8, 1, 16, "crypt"),
    (6, 15, 8, 1, 16, "crypt"),
    (7, 15, 8, 1, 16, "crypt"),
    (8, 14, 32, 1, 16, "mkpasswd"),
    (9, 13, 32, 1, 16, "mkpasswd"),
    (10, 10, 4, 2, 16, "crypt"),
    (11, 10, 8, 1, 0, "crypt"),
    (12, 10, 8, 1, 64, "crypt"),
]


def make(i, nl, r, p, octets, maker):
    pw = password(i)
    s = salt(i, octets)
    setting = "$7$" + A[nl] + enc30(r) + enc30(p) + s
    line = crypt.crypt(pw, setting)
    if maker == "mkpasswd":
        # mkpasswd takes a scrypt salt only as a whole `$7$` setting (-S).
        got = subprocess.run(["mkpasswd", "-m", "scrypt", "-S", setting, pw],
                             capture_output=True, text=True, check=True).stdout.strip()
        if got != line:
            raise SystemExit(f"row {i}: mkpasswd {got!r} differs from crypt {line!r}")
    if not line.startswith("$7$") or crypt.crypt(pw, line) != line:
        raise SystemExit(f"row {i}: crypt refused or did not round-trip: {line!r}")
    return line


def render():
    versions = open("/oracle-versions.txt").read().split("\n")
    lines = [make(*row) for row in ROWS]
    body = []
    body.append('//! check: run(exit=0, stdout="ubuntu strings: %d rows")' % (3 * len(ROWS)))
    body.append("//! phase: run")
    body.append("//! conforms: std.x.crypto.passwd, std.x.crypto.sha2")
    body.append("//!")
    body.append("//! sc80: `$7$` strings Ubuntu 24.04's crypt made, checked three ways:")
    body.append("//! `passwd.verify` accepts each with its password, rejects it with the")
    body.append("//! password one octet longer, and `passwd.hash` of the same password,")
    body.append("//! salt and cost gives the same string, byte for byte. Each password is")
    body.append("//! the first 20 hex digits of SHA-256(\"sc80 ubuntu fixture password")
    body.append("//! <row>\"), derived here at run time, and each salt is crypt's base-64")
    body.append("//! of the first 0, 16 or 64 octets of SHA-512(\"sc80 ubuntu fixture salt")
    body.append("//! <row>\"). The strings are generated test data: GENERATED by")
    body.append("//! `docs/sc80-witness/interop/ubuntu_fixture.py` in sc80's pinned image")
    body.append("//! with these packages:")
    for v in versions:
        if v:
            body.append("//!   " + v)
    body.append("//! The local record's `ubuntu-fixture` step regenerates them and")
    body.append("//! compares. Rows 8 and 9 sit at `mkpasswd -R 7` and `-R 6`'s costs")
    body.append("//! (r = 32), and `mkpasswd -m scrypt -S <setting>` made the same string.")
    body.append("//! Each row prints `FAIL <name>` when it is wrong,")
    body.append("//! and the program then exits 1. Native only: rows at N = 2^14 and")
    body.append("//! 2^15 exhaust the interpreter's and the checked tier's step budgets.")
    body.append("")
    body.append("use std.x.crypto.passwd")
    body.append("use std.x.crypto.sha2")
    body.append("")
    body.append(WOLF_HELPERS)
    body.append("fn main() -> int {")
    body.append("    var bad: int = 0")
    for (i, nl, r, p, octets, maker), line in zip(ROWS, lines):
        body.append(f"    let s{i} = \"{line}\"")
        body.append(f"    bad = bad + check({i}, {nl}, {r}, {p}, {octets}, s{i})")
    body.append("    if bad > 0 {")
    body.append("        return 1")
    body.append("    }")
    body.append(f'    print("ubuntu strings: {3 * len(ROWS)} rows")')
    body.append("    0")
    body.append("}")
    return "\n".join(body) + "\n"


WOLF_HELPERS = '''fn row(name: str, ok: bool) -> int {
    if ok {
        return 0
    }
    print("FAIL {name}")
    1
}

/// Row `i`'s password: the first 20 hex digits of SHA-256 of its label.
fn password(i: int) -> List[byte] {
    let hex = sha2.to_hex(sha2.sum256("sc80 ubuntu fixture password {i}".bytes()))
    hex[0..20].bytes()
}

/// Row `i`'s salt: crypt's base-64 of the first `octets` octets of
/// SHA-512 of its label (`passwd.gen_salt` for 16 and 64; empty for 0).
fn salt(i: int, octets: int) -> str {
    if octets == 0 {
        return ""
    }
    let d = sha2.sum512("sc80 ubuntu fixture salt {i}".bytes())
    var head = List[byte]()
    var k: int = 0
    while k < octets {
        (mut head).push(d[k])
        k = k + 1
    }
    passwd.gen_salt(head) else ""
}

fn check(i: int, n_log2: int, r: int, p: int, octets: int, line: str) -> int {
    let pw = password(i)
    var longer = List[byte]()
    for b in pw {
        (mut longer).push(b)
    }
    (mut longer).push(33 as byte)
    let accepted = passwd.verify(pw, line) else false
    let rejected = passwd.verify(longer, line) else true
    let c = passwd.cost(n_log2, r, p) else |_| {
        print("FAIL ubuntu-{i}-cost")
        return 1
    }
    let mine = passwd.hash(pw, salt(i, octets), c) else ""
    var bad: int = 0
    bad = bad + row("ubuntu-{i}-verifies", accepted)
    bad = bad + row("ubuntu-{i}-wrong-password-refused", !rejected)
    bad = bad + row("ubuntu-{i}-hash-identical", mine == line)
    bad
}
'''

if __name__ == "__main__":
    if sys.argv[1:2] == ["--check"]:
        want = open(sys.argv[2]).read()
        got = render()
        if got != want:
            print("FAIL ubuntu-fixture-drift")
            sys.exit(1)
        print(f"ok   {sys.argv[2]} regenerated identically ({len(ROWS)} strings)")
    else:
        open(sys.argv[1], "w").write(render())
